@ApiStatus.Internal
@NullMarked
public final class HCsCR {
    /**
     * Marker for all logs generated by the mod.
     */
    @UnknownNullability
    public static final Marker MARKER = (Variables.DEBUG_LOGS ? MarkerManager.getMarker("MOD_HCSCR") : null);

    /**
     * A channel identifier for servers to know that this mod is installed.
     */
    //? if >=1.21.1 || (forge && >=1.18.2 && (!1.20.2)) {
    public static final Identifier CHANNEL = Identifier.fromNamespaceAndPath("hcscr", "imhere");
    //?} else {
    /*public static final Identifier CHANNEL = new Identifier("hcscr", "imhere");
    *///?}

    /**
     * Logger for this class.
     */
    @UnknownNullability
    private static final Logger LOGGER = (Variables.DEBUG_LOGS ? LogManager.getLogger("HCsCR/HCsCR") : null);

    /**
     * An instance of this class cannot be created.
     *
     * @throws AssertionError Always
     * @deprecated Always throws
     */
    @ApiStatus.ScheduledForRemoval
    @Deprecated
    @Contract(value = "-> fail", pure = true)
    private HCsCR() {
        if (Variables.DEBUG_ASSERTS) {
            throw new AssertionError("HCsCR: No instances.");
        }
    }

    /**
     * Handles the client tick. (ending of a client tick)
     * <p>
     * Calls some handlers that depend on ticks.
     *
     * @param client Client game instance
     * @see Keys#tick(Minecraft, ProfilerFiller)
     * @see HiddenEntities#tick(Minecraft, ProfilerFiller)
     * @see BlockClips#tick(Minecraft, ProfilerFiller)
     */
    //~ if >=1.21.3 'client.getProfiler' -> 'Profiler.get' {
    public static void tick(final Minecraft client) {
        // Validate.
        if (Variables.DEBUG_ASSERTS) {
            assert (client != null) : "HCsCR: Parameter 'client' is null.";
            assert (client.isSameThread()) : "HCsCR: Wrong thread. (thread: " + Thread.currentThread() + ", client: " + client + ')';
        }

        // Get and push the profiler.
        final ProfilerFiller profiler;
        if (Variables.DEBUG_PROFILER) {
            profiler = Profiler.get();
            profiler.push("hcscr:tick");
        } else {
            profiler = null;
        }

        // Keys. (process key-bindings/key-mappings)
        Keys.tick(client, profiler); // Implicit NPE for 'client'

        // Hidden entities. (cleanup/resync)
        HiddenEntities.tick(client, profiler); // Implicit NPE for 'client'

        // Block clipping. (cleanup/resync)
        BlockClips.tick(client, profiler); // Implicit NPE for 'client'

        // Pop the profiler.
        if (Variables.DEBUG_PROFILER) {
            profiler.pop();
        }
    }

    /**
     * Handles the client main loop. (a single game frame)
     * <p>
     * Calls some handlers that depend on frames.
     *
     * @param client Client game instance
     * @see ScheduledEntities#loop(Minecraft, ProfilerFiller)
     */
    public static void loop(final Minecraft client) {
        // Validate.
        if (Variables.DEBUG_ASSERTS) {
            assert (client != null) : "HCsCR: Parameter 'client' is null.";
            assert (client.isSameThread()) : "HCsCR: Wrong thread. (thread: " + Thread.currentThread() + ", client: " + client + ')';
        }

        // Get and push the profiler.
        final ProfilerFiller profiler;
        if (Variables.DEBUG_PROFILER) {
            profiler = Profiler.get();
            profiler.push("hcscr:loop");
        } else {
            profiler = null;
        }

        // Scheduled entities. (cleanup/remove)
        ScheduledEntities.loop(client, profiler); // Implicit NPE for 'client'

        // Pop the profiler.
        if (Variables.DEBUG_PROFILER) {
            profiler.pop();
        }
    }

    /**
     * Handles the client respawn. (client level load, unload, or change)
     * <p>
     * Clears some handlers' data tied to levels.
     *
     * @param client Client game instance
     * @see ScheduledEntities#unscheduleAll()
     * @see HiddenEntities#showAll()
     * @see BlockClips#clearClips()
     */
    public static void respawn(final Minecraft client) {
        // Validate.
        if (Variables.DEBUG_ASSERTS) {
            assert (client != null) : "HCsCR: Parameter 'client' is null.";
            assert (client.isSameThread()) : "HCsCR: Wrong thread. (thread: " + Thread.currentThread() + ", client: " + client + ')';
        }

        // Get and push the profiler.
        final ProfilerFiller profiler;
        if (Variables.DEBUG_PROFILER) {
            profiler = Profiler.get();
            profiler.push("hcscr:respawn");
        } else {
            profiler = null;
        }

        // Log. (**TRACE**)
        if (Variables.DEBUG_LOGS) {
            LOGGER.trace(MARKER, "HCsCR: Clearing on respawn...");
        }

        // Unschedule (clear) all scheduled entities.
        ScheduledEntities.unscheduleAll();

        // Show (clear) all hidden entities.
        HiddenEntities.showAll();

        // Remove all block clips.
        BlockClips.clearClips();

        // Log. (**DEBUG**)
        if (Variables.DEBUG_LOGS) {
            LOGGER.debug(MARKER, "HCsCR: Cleared on respawn.");
        }

        // Pop the profiler.
        if (Variables.DEBUG_PROFILER) {
            profiler.pop();
        }
    }
    //~}
}
